# Pre-build step: gzip the embedded PAGE / SETUP_PAGE into src/page_gz.h.
#
# The ESP8266 WebServer does not compress responses on its own, and the main
# UI page is ~61KB of HTML+JS - over a weak WiFi link that is seconds of
# airtime per settings-page open.  This script extracts both raw literals
# from src/main.cpp, gzips them (deterministic: mtime=0) and emits PROGMEM
# byte arrays; handleRoot serves the compressed copy when the browser sends
# Accept-Encoding: gzip and keeps the raw literal as the curl fallback.
#
# The output file is rewritten ONLY when the bytes change, so a no-op build
# does not recompile main.cpp.  Run standalone (`python tools/mkpagegz.py`)
# or let PlatformIO invoke it via extra_scripts before every build.
import gzip
import io
import os
import re
import sys

try:
    Import("env")                       # PlatformIO / SCons pre-script context
    ROOT = env.Dir("#").abspath
except NameError:                       # standalone: python tools/mkpagegz.py
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "main.cpp")
OUT = os.path.join(ROOT, "src", "page_gz.h")


def extract(src, name):
    m = re.search(
        r'static const char %s\[\] PROGMEM = R"HTML\((.*?)\)HTML";' % name,
        src,
        re.S,
    )
    if not m:
        raise SystemExit("mkpagegz: raw literal %s not found in main.cpp" % name)
    return m.group(1)


def c_array(data, name):
    lines = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("  " + ", ".join("0x%02X" % b for b in chunk) + ",")
    return (
        "static const char %s[] PROGMEM = {\n%s\n};\n"
        "static const uint32_t %s_LEN = %d;\n" % (name, "\n".join(lines), name, len(data))
    )


def main():
    with io.open(SRC, encoding="utf-8", newline="") as f:
        src = f.read()
    parts = [
        "#pragma once",
        "// GENERATED by tools/mkpagegz.py - do not edit.",
        "// gzip copies of the embedded pages, served when the browser sends",
        "// Accept-Encoding: gzip; the raw literals in main.cpp stay as fallback.",
        "",
    ]
    total = 0
    for name in ("PAGE", "SETUP_PAGE"):
        html = extract(src, name).encode("utf-8")
        gz = gzip.compress(html, compresslevel=9, mtime=0)
        total += len(gz)
        parts.append("// %s: %d -> %d bytes" % (name, len(html), len(gz)))
        parts.append(c_array(gz, name + "_GZ"))
    new = "\n".join(parts)
    old = None
    if os.path.exists(OUT):
        try:
            with io.open(OUT, encoding="utf-8", newline="") as f:
                old = f.read()
        except Exception:
            old = None
    if old != new:
        with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(new)
        sys.stdout.write("mkpagegz: %d bytes of gzip written\n" % total)
    # unchanged -> silent: no pointless main.cpp recompile


main()
